/*
|--------------------------------------------------------------------------
| MODE OFFSETS
|--------------------------------------------------------------------------
|
| We intentionally use 100-word blocks.
|
*/

const MODE_OFFSETS = {
  easy: 0,
  medium: 100,
  hard: 200,
  difficult: 300
};


/*
|--------------------------------------------------------------------------
| GET WORD FOR LEVEL
|--------------------------------------------------------------------------
*/

export function getWordForLevel(
  mode,
  level
) {
  const normalizedMode =
    String(mode || "")
      .toLowerCase();

  const numericLevel =
    Number(level);


  if (
    !MODE_OFFSETS.hasOwnProperty(
      normalizedMode
    )
  ) {
    throw new Error(
      `Invalid game mode: ${mode}`
    );
  }


  if (
    !Number.isInteger(
      numericLevel
    ) ||
    numericLevel < 1 ||
    numericLevel > 100
  ) {
    throw new Error(
      `Invalid level: ${level}`
    );
  }


  const index =
    MODE_OFFSETS[normalizedMode] +
    numericLevel -
    1;


  const word =
    WORDS[index];


  if (!word) {
    throw new Error(
      `Word not found for ${normalizedMode} level ${numericLevel}`
    );
  }


  return word;
}


